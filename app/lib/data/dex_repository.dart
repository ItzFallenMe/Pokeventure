/// The whole offline dataset: 1,025 species, every move and the six zones.
class DexCatalog {
  DexCatalog({
    required this.species,
    required this.zones,
    required this.moves,
    this.version = 0,
  }) : byNumber = {for (final entry in species) entry.number: entry},
       byName = {for (final entry in species) entry.name.toLowerCase(): entry};

  factory DexCatalog.empty() {
    return DexCatalog(species: const [], zones: const [], moves: const {});
  }

  final List<DexEntry> species;
  final List<Zone> zones;
  final Map<String, MoveEntry> moves;
  final int version;
  final Map<int, DexEntry> byNumber;
  final Map<String, DexEntry> byName;

  bool get isLoaded => species.isNotEmpty;

  DexEntry? speciesAt(int number) => byNumber[number];

  DexEntry? speciesNamed(String name) => byName[name.toLowerCase()];

  MoveEntry? move(String name) => moves[name.toLowerCase()];

  Zone? zone(String slug) {
    for (final zone in zones) {
      if (zone.slug == slug) return zone;
    }
    return null;
  }
}

String cleanFlavour(String raw) {
  return raw
      .replaceAll(RegExp(r'[\n\r\f]+'), ' ')
      .replaceAll(RegExp(r'\s+'), ' ')
      .trim();
}

/// Reads the JSON snapshots generated by `tools/gen-dex.mjs`.
Future<DexCatalog> loadDexCatalog({AssetBundle? bundle}) async {
  final assets = bundle ?? rootBundle;

  final dexRaw = jsonDecode(await assets.loadString('assets/data/dex.json'));
  final List<dynamic> rawSpecies;
  var version = 0;
  if (dexRaw is Map<String, dynamic>) {
    rawSpecies = (dexRaw['species'] as List<dynamic>?) ?? const [];
    version = (dexRaw['version'] as num?)?.toInt() ?? 0;
  } else {
    rawSpecies = dexRaw as List<dynamic>;
  }
  final species = rawSpecies
      .map((raw) => DexEntry.fromJson(raw as Map<String, dynamic>))
      .toList(growable: false);

  final movesRaw = jsonDecode(
    await assets.loadString('assets/data/moves.json'),
  );
  final moves = <String, MoveEntry>{
    for (final raw in (movesRaw as List<dynamic>))
      (raw as Map<String, dynamic>)['name'].toString().toLowerCase():
          MoveEntry.fromJson(raw),
  };

  List<Zone> zones = const [];
  try {
    final zonesRaw = jsonDecode(
      await assets.loadString('assets/data/zones.json'),
    );
    zones = (zonesRaw as List<dynamic>)
        .map((raw) => Zone.fromJson(raw as Map<String, dynamic>))
        .toList(growable: false);
  } on Object {
    zones = const [];
  }

  return DexCatalog(
    species: species,
    zones: zones,
    moves: moves,
    version: version,
  );
}

/// Overridden in `main()` after the assets load. Tests can override it with a
/// fixture or with the real dataset.
final dexCatalogProvider = Provider<DexCatalog>((ref) => DexCatalog.empty());

final dexProvider = FutureProvider<List<DexEntry>>((ref) async {
  return ref.watch(dexCatalogProvider).species;
});

final moveLookupProvider = FutureProvider<Map<String, MoveEntry>>((ref) async {
  return ref.watch(dexCatalogProvider).moves;
});

/// Species name (lowercase) → entry, for battle sprites and types.
final dexLookupProvider = FutureProvider<Map<String, DexEntry>>((ref) async {
  return ref.watch(dexCatalogProvider).byName;
});

/// Species numbers the trainer has caught (registered in the dex).
final ownedDexProvider = Provider<Set<int>>((ref) {
  return ref.watch(trainerProvider).caught;
});

/// Species numbers the trainer has seen in the wild.
final seenDexProvider = Provider<Set<int>>((ref) {
  return ref.watch(trainerProvider).seen;
});
